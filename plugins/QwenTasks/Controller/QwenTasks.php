<?php

namespace Kanboard\Plugin\QwenTasks\Controller;

use Kanboard\Controller\BaseController;
use Kanboard\Core\Controller\AccessForbiddenException;

class QwenTasks extends BaseController
{
    public function index(array $values = array(), array $errors = array())
    {
        $projects = $this->getAllowedProjects();

        $this->response->html($this->helper->layout->app('QwenTasks:index', array(
            'title' => t('Qwen Tasks (Beta)'),
            'projects' => $projects,
            'values' => $values,
            'errors' => $errors,
        )));
    }

    public function create()
    {
        $values = $this->request->getValues();
        $projectId = isset($values['project_id']) ? (int) $values['project_id'] : 0;
        $json = isset($values['tasks_json']) ? trim($values['tasks_json']) : '';
        $errors = array();

        if (! $this->canUseProject($projectId)) {
            throw new AccessForbiddenException();
        }

        if ($json === '') {
            $errors[] = t('Paste the JSON generated by Qwen.');
        } else {
            $payload = json_decode($json, true);
            if (! is_array($payload) || json_last_error() !== JSON_ERROR_NONE) {
                $errors[] = t('The pasted content is not valid JSON.');
            } else {
                $tasks = isset($payload['tasks']) && is_array($payload['tasks']) ? $payload['tasks'] : $payload;
                $created = $this->createTasks($projectId, $tasks, $errors);

                if ($created > 0 && empty($errors)) {
                    $this->flash->success(t('%d tasks created successfully.', $created));
                    return $this->response->redirect($this->helper->url->to('QwenTasks', 'index', array('plugin' => 'QwenTasks')));
                }
            }
        }

        $values['tasks_json'] = $json;
        $this->index($values, $errors);
    }

    private function createTasks($projectId, $tasks, array &$errors)
    {
        if (! is_array($tasks) || count($tasks) === 0) {
            $errors[] = t('The JSON must contain a non-empty tasks array.');
            return 0;
        }

        if (count($tasks) > 50) {
            $errors[] = t('A maximum of 50 tasks can be created at once.');
            return 0;
        }

        $created = 0;
        foreach ($tasks as $position => $task) {
            if (! is_array($task)) {
                $errors[] = t('Task %d is not an object.', $position + 1);
                continue;
            }

            $titleValue = $task['title'] ?? '';
            $title = is_scalar($titleValue) ? trim((string) $titleValue) : '';
            if ($title === '') {
                $errors[] = t('Task %d has no title.', $position + 1);
                continue;
            }

            $columnId = isset($task['column_id']) ? (int) $task['column_id'] : 0;
            if ($columnId === 0) {
                $columnId = (int) $this->columnModel->getFirstColumnId($projectId);
            }

            if ($this->columnModel->getProjectId($columnId) != $projectId || ! $this->helper->projectRole->canCreateTaskInColumn($projectId, $columnId)) {
                $errors[] = t('Task %d targets a column where you cannot create tasks.', $position + 1);
                continue;
            }

            $tags = $task['tags'] ?? array();
            if (is_string($tags)) {
                $tags = array_filter(array_map('trim', explode(',', $tags)));
            }
            if (! is_array($tags)) {
                $tags = array();
            }
            $tags = array_values(array_filter($tags, 'is_scalar'));

            $taskValues = array(
                'project_id' => $projectId,
                'column_id' => $columnId,
                'title' => substr($title, 0, 255),
                'description' => substr(is_scalar($task['description'] ?? '') ? (string) ($task['description'] ?? '') : '', 0, 10000),
                'color_id' => substr(is_scalar($task['color_id'] ?? '') ? (string) ($task['color_id'] ?? '') : '', 0, 50),
                'tags' => array_slice($tags, 0, 20),
            );

            if ($this->taskCreationModel->create($taskValues) > 0) {
                $created++;
            }
        }

        return $created;
    }

    private function canUseProject($projectId)
    {
        return $projectId > 0 && $this->helper->user->hasProjectAccess('TaskCreationController', 'show', $projectId);
    }

    private function getAllowedProjects()
    {
        if ($this->userSession->isAdmin()) {
            return $this->projectModel->getList(false, false);
        }

        return $this->projectUserRoleModel->getProjectsByUser($this->userSession->getId(), array(1));
    }
}
